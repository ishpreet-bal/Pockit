export interface LexiconMatch {
  slug: string;
  display: string | null;
  confidence: number;
}

/**
 * The pattern must start a word: "esso" is the gas station, not the middle of
 * "espresso", and "shell" isn't inside "Michelle". It may run on into more letters
 * ("tim horton" matches "Tim Hortons"), since bank text often adds a store number.
 */
function startsWord(haystack: string, pattern: string): boolean {
  let at = haystack.indexOf(pattern);
  while (at !== -1) {
    if (at === 0 || !/[a-z0-9]/.test(haystack[at - 1]!)) return true;
    at = haystack.indexOf(pattern, at + 1);
  }
  return false;
}

/** Longest-pattern-wins lookup, so "uber eats" beats "uber". */
export function lookupMerchant(text: string): LexiconMatch | null {
  const haystack = text.toLowerCase();
  let best: { pattern: string; slug: string; display?: string } | null = null;
  for (const entry of MERCHANT_LEXICON) {
    if (!startsWord(haystack, entry.pattern)) continue;
    if (!best || entry.pattern.length > best.pattern.length) best = entry;
  }
  if (!best) return null;
  return {
    slug: best.slug,
    display: best.display ?? null,
    // Longer matches are more specific and therefore more trustworthy.
    confidence: Math.min(95, 70 + best.pattern.length * 2),
  };
}
